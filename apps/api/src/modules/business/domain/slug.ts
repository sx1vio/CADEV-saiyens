/** Identifiant d'URL d'une entreprise : « Wave Mobile Money » → « wave-mobile-money ». */
export function companySlug(name: string): string {
  const s = name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 48);
  return s || 'entreprise';
}
